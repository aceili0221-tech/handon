#!/bin/bash
# ==============================================================================
# 🏢 企業內部出勤與工時打卡系統 - Linux 啟動腳本
# ==============================================================================

cd "$(dirname "$0")" || exit 1

echo ""
echo "================================================================="
echo "  🏢 企業內部出勤與工時打卡系統 - 本地啟動程式 (Linux)"
echo "================================================================="
echo ""

if ! command -v node &> /dev/null; then
  echo "❌ 錯誤：找不到 Node.js！請先安裝 Node.js。"
  exit 1
fi

if [ ! -d "node_modules" ]; then
  echo "📦 正在安裝依賴套件..."
  npm install
fi

echo "🚀 正在啟動伺服器並開啟瀏覽器..."
npm run start:browser
